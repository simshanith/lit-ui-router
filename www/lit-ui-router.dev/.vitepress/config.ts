export default defineConfig({
  ...config,
  transformHead({ pageData }) {
    const head: HeadConfig[] = [];
    const imageUrl = `${baseUrl}${SOCIAL_CARD.path}`;
    const twitterCreator = '@simloovoo';
    const twitterCard = 'summary_large_image';
    const ogType = 'website';

    let title: string;
    let description: string;
    let pageUrl: string;

    if (pageData.relativePath === 'index.md') {
      title = config.title;
      description = config.description;
      pageUrl = baseUrl;
    } else {
      // SAFETY: frontmatter is Record<string, any>; title and description are strings when set
      title =
        (pageData.frontmatter.title as string | undefined) || pageData.title;
      title = title ? `${config.title} - ${title}` : config.title;

      // SAFETY: as for the frontmatter title
      description =
        (pageData.frontmatter.description as string | undefined) ||
        pageData.description ||
        config.description;

      const pagePath = pageData.relativePath
        .replace(/^\.\//, '')
        .replace(/\/index\.md$/, '/')
        .replace(/\.md$/, '');

      pageUrl = `${baseUrl}/${pagePath}`;
    }

    head.push(
      ['meta', { property: 'og:title', content: title }],
      ['meta', { property: 'og:description', content: description }],
      ['meta', { property: 'og:image', content: imageUrl }],
      [
        'meta',
        { property: 'og:image:width', content: String(SOCIAL_CARD.width) },
      ],
      [
        'meta',
        { property: 'og:image:height', content: String(SOCIAL_CARD.height) },
      ],
      ['meta', { property: 'og:image:alt', content: SOCIAL_CARD.alt }],
      ['meta', { property: 'og:url', content: pageUrl }],
      ['meta', { property: 'og:type', content: ogType }],
      ['meta', { property: 'og:site_name', content: config.title }],
      ['meta', { name: 'twitter:card', content: twitterCard }],
      ['meta', { name: 'twitter:creator', content: twitterCreator }],
      ['meta', { name: 'twitter:title', content: title }],
      ['meta', { name: 'twitter:description', content: description }],
      ['meta', { name: 'twitter:image', content: imageUrl }],
      ['meta', { name: 'twitter:image:alt', content: SOCIAL_CARD.alt }],
    );

    return head;
  },
});
