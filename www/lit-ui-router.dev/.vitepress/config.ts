type ReferenceLink = NonNullable<(typeof API_REFERENCES)[PackageName]>;

// Keyed by reference link, so a new reference fails typecheck until it has generated items.
const REFERENCE_ITEMS: Record<ReferenceLink, DefaultTheme.SidebarItem[]> = {
  '/api/reference/': typedocSidebarItems,
  '/api/ui-router-effect/': uiRouterEffectSidebarItems,
  '/api/lit-ui-router-effect/': effectSidebarItems,
  '/api/ui-router-mobx/': uiRouterMobxSidebarItems,
  '/api/lit-ui-router-mobx/': mobxSidebarItems,
  '/api/ui-router-signals/': uiRouterSignalsSidebarItems,
  '/api/lit-ui-router-signals/': signalsSidebarItems,
  '/api/navigation-location-plugin/': navigationSidebarItems,
  '/api/ui-router-server/': serverSidebarItems,
  '/api/lit-ui-router-ssr/': ssrSidebarItems,
  '/api/ui-router-registry/': uiRouterRegistrySidebarItems,
};

const referenceItems = new Map<string, DefaultTheme.SidebarItem[]>(
  Object.entries(REFERENCE_ITEMS),
);

/** The catalog sidebar, each API reference entry given its generated members. */
function withReferences(entries: SidebarEntry[]): DefaultTheme.SidebarItem[] {
  return entries.map((entry) => {
    const reference = entry.link && referenceItems.get(entry.link);

    if (reference) return { ...entry, items: reference };

    return entry.items
      ? { ...entry, items: withReferences(entry.items) }
      : entry;
  });
}

