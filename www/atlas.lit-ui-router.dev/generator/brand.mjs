// THE CLIENT'S MARK — the lit-ui-router logo and the Lit flame it glows with,
// the pair the docs site's home hero draws (www/lit-ui-router.dev/index.md and
// its theme's `--vp-home-hero-image-*` tokens). The cover stamps the client's
// name; this is the client's mark beside it. Both files are the docs site's
// own, copied under generator/brand/, and ride into the app as data URIs
// through the generated module, so the prerender, the site and the artifact
// all carry them with no request.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = fileURLToPath(new URL('.', import.meta.url));

/** An SVG file as a data URI: the markup percent-encoded, which beats base64 for text. */
const dataUri = (file) =>
  `data:image/svg+xml,${encodeURIComponent(readFileSync(join(HERE, 'brand', file), 'utf8').trim())}`;

const GENERATED =
  '// GENERATED by www/atlas.lit-ui-router.dev/generator/emit-app.mjs from generator/brand.mjs — do not edit.\n';

/** app/src/generated/brand.js: the two marks, as data. */
export const brandModule = () =>
  GENERATED +
  `export const LOGO_URL = ${JSON.stringify(dataUri('lit-ui-router.svg'))};\n` +
  `export const FLAME_URL = ${JSON.stringify(dataUri('lit-flame.svg'))};\n`;

/** app/src/generated/brand.d.ts */
export const BRAND_DTS =
  GENERATED +
  "/** The lit-ui-router logo, the docs site's own file, as a data URI. */\n" +
  'export declare const LOGO_URL: string;\n' +
  '/** The Lit flame the logo glows with, as a data URI. */\n' +
  'export declare const FLAME_URL: string;\n';
